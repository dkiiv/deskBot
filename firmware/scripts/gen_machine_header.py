#!/usr/bin/env python3
"""Embed a machine profile JSON into a C header the firmware can compile.

Why a generated header and not a runtime parse of a file:
  * there is no filesystem in this build (no LittleFS/SPIFFS partition is
    reserved for it) and the profile must be valid before the first tick, so
    the honest place for it is flash;
  * the JSON *text* is embedded verbatim (as a raw string literal) and parsed
    at boot by firmware/include/deskbot/json_embed.h - the same document the
    host simulator loads, so there is exactly one source of truth for the
    numbers and no second hand-maintained copy of the constants.

Usage (from firmware/):
    python3 scripts/gen_machine_header.py ../machines/husky-46x24.machine.json
writes  firmware/include/generated/machine_profile_json.h  (committed on
purpose: `pio run` must build with no python step and no repo-relative paths).

The generator refuses a payload containing the raw-literal terminator and
checks the required profile keys, so a broken profile fails here rather than
booting a desk with defaulted scale factors.
"""
import json
import os
import sys

REQUIRED_AXIS = ["steps_per_motor_rev", "gear_ratio", "mm_per_shaft_rev",
                 "travel_low_mm", "travel_high_mm"]


def die(msg):
    sys.stderr.write("gen_machine_header: %s\n" % msg)
    sys.exit(1)


def main():
    if len(sys.argv) != 2:
        die("usage: gen_machine_header.py <machine.json>")
    src = sys.argv[1]
    text, data = load(src)

    axes = data.get("axes")
    if not isinstance(axes, list) or not (1 <= len(axes) <= 2):
        die("'axes' must be a 1..2 element array (found %r)" % (axes,))
    assert isinstance(axes, list)  # narrows for static type checkers
    for i, ax in enumerate(axes):
        for key in REQUIRED_AXIS:
            if key not in ax:
                die("axis %d missing required key %r" % (i, key))
    identity = data.get("identity")
    if not isinstance(identity, dict) or "name" not in identity:
        die("identity.name is required")
    assert isinstance(identity, dict)  # narrows for static type checkers

    # A raw string literal R"DBOTJSON(...)DBOTJSON" survives anything except a
    # sequence equal to )DBOTJSON" in the payload, which no profile contains.
    marker = "DBOTJSON"
    if (")" + marker + '"') in text:
        die("payload contains the raw-literal terminator")
    if "\\" in text:
        die("payload contains a backslash; not expected in a machine profile")

    out_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "..", "include", "generated")
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.normpath(os.path.join(out_dir, "machine_profile_json.h"))
    name = identity["name"]
    version = identity.get("profile_version", 1)

    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("// GENERATED by scripts/gen_machine_header.py - do not edit.\n")
        fh.write("// Source: ../../%s\n" % os.path.relpath(
            os.path.abspath(src), os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")))
        fh.write("//\n")
        fh.write("// The profile text below is the only copy of this machine's\n")
        fh.write("// numbers in the firmware; it is parsed at boot by\n")
        fh.write("// deskbot/json_embed.h + deskbot/profile_embed.h. Regenerate\n")
        fh.write("// after editing the JSON, and keep the committed header in sync\n")
        fh.write("// (tests/firmware/firmware_host_tests.cpp recompiles it every\n")
        fh.write("//  run, and tests/firmware/host_loader_tu.cpp checks the two\n")
        fh.write("//  profile loaders still agree on every field).\n")
        fh.write("#pragma once\n\n")
        fh.write("#define DESKBOT_MACHINE_NAME %s\n" % json.dumps(name))
        fh.write("#define DESKBOT_MACHINE_PROFILE_VERSION %d\n\n" % int(version))
        fh.write("static const char kMachineJson[] = R\"%s(\n%s\n)%s\";\n"
                 % (marker, text.rstrip("\n"), marker))
    sys.stderr.write("gen_machine_header: wrote %s (%s v%s)\n"
                     % (out_path, name, version))


def load(src):
    try:
        with open(src, "r", encoding="utf-8") as fh:
            text = fh.read()
        return text, json.loads(text)
    except Exception as exc:                       # noqa: BLE001 - report all
        die("cannot read %s: %s" % (src, exc))
        return "", {}                              # unreachable


if __name__ == "__main__":
    main()
